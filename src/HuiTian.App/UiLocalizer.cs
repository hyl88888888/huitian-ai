    public static void SetSkip(DependencyObject element, bool value) => element.SetValue(SkipProperty, value);

    public static bool GetSkip(DependencyObject element) => (bool)element.GetValue(SkipProperty);

    public static string Translate(string language, string source)
    {
        var dictionary = language switch
        {
            "en-US" => English,
            "ja-JP" => Japanese,
            _ => null,
        };
        return dictionary is not null && dictionary.TryGetValue(source, out var translated)
            ? translated
            : source;
    }

    public static void Apply(DependencyObject root, string language)
    {
        var visited = new HashSet<DependencyObject>(ReferenceEqualityComparer.Instance);
        ApplyCore(root, language, visited);
    }

    private static void ApplyCore(
        DependencyObject element,
        string language,
        HashSet<DependencyObject> visited)
    {
        if (!visited.Add(element) || GetSkip(element))
        {
            return;
        }

        var original = Originals.GetOrCreateValue(element);
        if (element is TextBlock textBlock &&
            !BindingOperations.IsDataBound(textBlock, TextBlock.TextProperty))
        {
            original.TextSource = RefreshSource(textBlock.Text, original.TextSource, original.TextLastApplied);
            textBlock.Text = Translate(language, original.TextSource);
            original.TextLastApplied = textBlock.Text;
        }

        if (element is ContentControl contentControl && contentControl.Content is string content &&
            !BindingOperations.IsDataBound(contentControl, ContentControl.ContentProperty))
        {
            original.ContentSource = RefreshSource(content, original.ContentSource, original.ContentLastApplied);
            contentControl.Content = Translate(language, original.ContentSource);
            original.ContentLastApplied = contentControl.Content as string;
        }

        if (element is HeaderedContentControl headered && headered.Header is string header)
        {
            original.HeaderSource = RefreshSource(header, original.HeaderSource, original.HeaderLastApplied);
            headered.Header = Translate(language, original.HeaderSource);
            original.HeaderLastApplied = headered.Header as string;
        }

        if (element is FrameworkElement framework && framework.ToolTip is string toolTip)
        {
            original.ToolTipSource = RefreshSource(toolTip, original.ToolTipSource, original.ToolTipLastApplied);
            framework.ToolTip = Translate(language, original.ToolTipSource);
            original.ToolTipLastApplied = framework.ToolTip as string;
        }

        foreach (var child in LogicalTreeHelper.GetChildren(element).OfType<DependencyObject>())
        {
            ApplyCore(child, language, visited);
        }
    }

    private static string RefreshSource(string current, string? source, string? lastApplied) =>
        source is null || !string.Equals(current, lastApplied, StringComparison.Ordinal)
            ? current
            : source;
